from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from PySide6.QtCore import Signal
from PySide6.QtWidgets import (
    QButtonGroup,
    QFileDialog,
    QFrame,
    QGridLayout,
    QHBoxLayout,
    QLabel,
    QLineEdit,
    QPushButton,
    QRadioButton,
    QScrollArea,
    QVBoxLayout,
    QWidget,
)


_DEFAULT_ANALYSIS_MODES = [
    {
        "id": "within",
        "title": "Within subject",
        "description": "Compare repeated conditions or sessions from the same participants. Each participant acts as their own control.",
    },
    {
        "id": "between",
        "title": "Between subjects",
        "description": "Compare independent participant groups. Differences reflect variation between groups.",
    },
    {
        "id": "nocomparison",
        "title": "No comparison",
        "description": "Inspect one participant or recording descriptively, without group or condition comparisons.",
    },
]


class PlotFeaturesLoadDataWidget(QScrollArea):
    changed = Signal()

    def __init__(self, experiment_info: dict, defaults: dict, state: dict):
        del experiment_info
        super().__init__()

        self.state = state
        self.config = defaults.get("load_features", {})
        self.required_folder_name = str(self.config.get("required_folder_name", "derivatives"))
        self.required_config_file = str(self.config.get("required_config_file", "config.json"))
        self.analysis_modes = self._analysis_mode_definitions()
        self.option_frames: dict[str, QFrame] = {}

        self.setWidgetResizable(True)
        self.setFrameShape(QFrame.Shape.NoFrame)

        self.content = QWidget()
        self.setWidget(self.content)
        root = QVBoxLayout(self.content)
        root.setContentsMargins(4, 4, 4, 4)
        root.setSpacing(18)

        title = QLabel("Load feature data")
        title.setObjectName("pageTitle")
        description = QLabel("Select the derivatives folder generated by a previous analysis pipeline.")
        description.setObjectName("muted")
        description.setWordWrap(True)
        root.addWidget(title)
        root.addWidget(description)

        root.addWidget(self._build_folder_panel())
        root.addWidget(self._build_analysis_panel())
        root.addWidget(self._build_metadata_panel())
        root.addStretch()

        self._restore_analysis_mode()
        self._restore_loaded_state()

    def _build_folder_panel(self) -> QFrame:
        panel = QFrame()
        panel.setProperty("role", "surface-panel")
        layout = QVBoxLayout(panel)
        layout.setContentsMargins(24, 22, 24, 22)
        layout.setSpacing(12)

        heading = QLabel("Feature folder")
        heading.setObjectName("panelTitle")
        layout.addWidget(heading)

        row = QHBoxLayout()
        row.setContentsMargins(0, 0, 0, 0)
        self.path_display = QLineEdit()
        self.path_display.setReadOnly(True)
        self.path_display.setPlaceholderText("No derivatives folder selected")
        browse_button = QPushButton("Browse")
        browse_button.setProperty("variant", "secondary")
        browse_button.clicked.connect(self._browse_derivatives_folder)
        row.addWidget(self.path_display, 1)
        row.addWidget(browse_button)
        layout.addLayout(row)

        self.status_label = QLabel("Select a derivatives folder that contains config.json.")
        self.status_label.setObjectName("selectionStatus")
        self.status_label.setProperty("status", "idle")
        self.status_label.setWordWrap(True)
        layout.addWidget(self.status_label)

        return panel

    def _build_analysis_panel(self) -> QFrame:
        panel = QFrame()
        panel.setProperty("role", "surface-panel")
        layout = QVBoxLayout(panel)
        layout.setContentsMargins(24, 22, 24, 22)
        layout.setSpacing(12)

        heading = QLabel("Select Analysis Type")
        heading.setObjectName("panelTitle")
        layout.addWidget(heading)

        self.analysis_group = QButtonGroup(self)
        self.analysis_group.setExclusive(True)
        self.analysis_group.buttonToggled.connect(self._analysis_mode_changed)

        for mode in self.analysis_modes:
            option = QFrame()
            option.setProperty("role", "analysis-mode-option")
            option_layout = QVBoxLayout(option)
            option_layout.setContentsMargins(16, 14, 16, 14)
            option_layout.setSpacing(6)

            radio = QRadioButton(str(mode["title"]))
            radio.setProperty("role", "analysis-mode-radio")
            radio.setProperty("analysis_mode", str(mode["id"]))
            radio.setToolTip(str(mode["description"]))
            self.analysis_group.addButton(radio)

            detail = QLabel(str(mode["description"]))
            detail.setObjectName("analysisModeDescription")
            detail.setWordWrap(True)

            option_layout.addWidget(radio)
            option_layout.addWidget(detail)
            layout.addWidget(option)
            self.option_frames[str(mode["id"])] = option

        return panel

    def _build_metadata_panel(self) -> QFrame:
        self.metadata_panel = QFrame()
        self.metadata_panel.setProperty("role", "surface-panel")
        self.metadata_layout = QGridLayout(self.metadata_panel)
        self.metadata_layout.setContentsMargins(24, 20, 24, 20)
        self.metadata_layout.setHorizontalSpacing(18)
        self.metadata_layout.setVerticalSpacing(8)
        self.metadata_panel.hide()
        return self.metadata_panel

    def _analysis_mode_definitions(self) -> list[dict[str, str]]:
        configured_modes = self.config.get("analysis_modes") or _DEFAULT_ANALYSIS_MODES
        modes: list[dict[str, str]] = []
        for mode in configured_modes:
            mode_id = str(mode.get("id", "")).strip()
            if not mode_id:
                continue
            modes.append({
                "id": mode_id,
                "title": str(mode.get("title", mode_id)),
                "description": str(mode.get("description", "")),
            })
        return modes or list(_DEFAULT_ANALYSIS_MODES)

    def _restore_analysis_mode(self) -> None:
        default_mode = str(self.config.get("default_analysis_mode", "within"))
        selected_mode = str(self.state.get("analysis_mode") or default_mode)
        selected_button = None
        fallback_button = None
        for button in self.analysis_group.buttons():
            mode_id = str(button.property("analysis_mode"))
            if mode_id == default_mode:
                fallback_button = button
            if mode_id == selected_mode:
                selected_button = button
        (selected_button or fallback_button or self.analysis_group.buttons()[0]).setChecked(True)
        self._sync_analysis_mode()

    def _restore_loaded_state(self) -> None:
        path = self.state.get("derivatives_path")
        channel_names = self.state.get("channel_names")
        if not path or not channel_names:
            return

        self.path_display.setText(str(path))
        metadata = self.state.get("plot_features_metadata")
        if isinstance(metadata, dict):
            self._show_metadata(metadata)
        self._set_status("Derivatives folder loaded.", "ready")

    def _browse_derivatives_folder(self) -> None:
        current_path = str(self.state.get("derivatives_path") or "")
        selected_path = QFileDialog.getExistingDirectory(self, "Select derivatives folder", current_path)
        if selected_path:
            self._load_derivatives_folder(Path(selected_path))

    def _load_derivatives_folder(self, path: Path) -> None:
        try:
            derivatives_path = path.resolve()
            if not derivatives_path.is_dir():
                raise ValueError("The selected path is not a folder.")
            if derivatives_path.name.lower() != self.required_folder_name.lower():
                raise ValueError("Select the derivatives folder generated by the analysis pipeline.")

            config_path = derivatives_path / self.required_config_file
            if not config_path.is_file():
                raise ValueError(f"The selected derivatives folder must contain {self.required_config_file}.")

            try:
                config_data = json.loads(config_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError) as exc:
                raise ValueError(f"{self.required_config_file} could not be read.") from exc

            channel_names = self._extract_channel_names(config_data)
            if not channel_names:
                raise ValueError(f"{self.required_config_file} does not contain channel names.")

            feature_files = self._discover_feature_files(derivatives_path)
            metadata = self._build_metadata(derivatives_path, config_path, config_data, channel_names, feature_files)
            self._apply_loaded_state(derivatives_path, config_path, config_data, channel_names, feature_files, metadata)
        except ValueError as exc:
            self._clear_loaded_state()
            self._set_status(str(exc), "error")
            self.changed.emit()

    def _apply_loaded_state(
        self,
        derivatives_path: Path,
        config_path: Path,
        config_data: dict[str, Any],
        channel_names: list[str],
        feature_files: list[str],
        metadata: dict[str, Any],
    ) -> None:
        path_text = str(derivatives_path)
        self.path_display.setText(path_text)
        self.state["input_data"] = [path_text]
        self.state["derivatives_path"] = path_text
        self.state["pipeline_config_path"] = str(config_path)
        self.state["plot_features_config"] = config_data
        self.state["channel_names"] = channel_names
        self.state["feature_files"] = feature_files
        self.state["plot_features_metadata"] = metadata
        self.state["metadata"] = metadata
        self._populate_plot_feature_items(config_data, feature_files)
        self._sync_analysis_mode(emit_changed=False)
        self._show_metadata(metadata)
        self._set_status("Derivatives folder loaded.", "ready")
        self.changed.emit()

    def _clear_loaded_state(self) -> None:
        self.path_display.clear()
        self.metadata_panel.hide()
        self.state["input_data"] = []
        for key in (
            "derivatives_path",
            "pipeline_config_path",
            "plot_features_config",
            "channel_names",
            "feature_files",
            "plot_features_metadata",
            "plot_features_subjects",
            "plot_features_recordings",
            "metadata",
        ):
            self.state.pop(key, None)

    def _analysis_mode_changed(self) -> None:
        self._sync_analysis_mode()

    def _sync_analysis_mode(self, emit_changed: bool = True) -> None:
        mode_id = self._current_analysis_mode()
        self.state["analysis_mode"] = mode_id
        for option_mode, frame in self.option_frames.items():
            frame.setProperty("selected", option_mode == mode_id)
            frame.style().unpolish(frame)
            frame.style().polish(frame)
        if emit_changed:
            self.changed.emit()

    def _current_analysis_mode(self) -> str:
        button = self.analysis_group.checkedButton()
        if button is None:
            return str(self.config.get("default_analysis_mode", "within"))
        return str(button.property("analysis_mode"))

    def _set_status(self, text: str, status: str) -> None:
        self.status_label.setText(text)
        self.status_label.setProperty("status", status)
        self.status_label.style().unpolish(self.status_label)
        self.status_label.style().polish(self.status_label)

    def _show_metadata(self, metadata: dict[str, Any]) -> None:
        while self.metadata_layout.count():
            item = self.metadata_layout.takeAt(0)
            if item.widget():
                item.widget().deleteLater()

        if not metadata:
            self.metadata_panel.hide()
            return

        for index, (label, value) in enumerate(metadata.items()):
            name = QLabel(str(label))
            name.setObjectName("metricLabel")
            metric = QLabel(self._format_value(value))
            metric.setObjectName("metricValue")
            metric.setWordWrap(True)
            self.metadata_layout.addWidget(name, (index // 3) * 2, index % 3)
            self.metadata_layout.addWidget(metric, (index // 3) * 2 + 1, index % 3)
        self.metadata_panel.show()

    def _build_metadata(
        self,
        derivatives_path: Path,
        config_path: Path,
        config_data: dict[str, Any],
        channel_names: list[str],
        feature_files: list[str],
    ) -> dict[str, Any]:
        config_metadata = config_data.get("metadata") if isinstance(config_data.get("metadata"), dict) else {}
        return {
            "Derivatives folder": derivatives_path.name,
            "Config file": config_path.name,
            "Channels": len(channel_names),
            "Channel names": channel_names,
            "Subjects": config_metadata.get("subjects", []),
            "Sessions": config_metadata.get("sessions", []),
            "Selected features": config_data.get("selected_features", []),
            "Feature files": len(feature_files),
        }

    def _discover_feature_files(self, derivatives_path: Path) -> list[str]:
        allowed_extensions = {str(ext).lower() for ext in self.config.get("allowed_extensions", [])}
        files: list[str] = []
        for file_path in derivatives_path.rglob("*"):
            if not file_path.is_file() or file_path.name == self.required_config_file:
                continue
            if allowed_extensions and file_path.suffix.lower() not in allowed_extensions:
                continue
            files.append(str(file_path))
        return sorted(files)

    def _populate_plot_feature_items(self, config_data: dict[str, Any], feature_files: list[str]) -> None:
        def format_subject(subject: str) -> str:
            text = subject.strip()
            return text if not text or text.startswith("sub-") else f"sub-{text}"

        def subjects_from_path(path: str) -> list[str]:
            subjects: list[str] = []
            for part in Path(path).parts:
                if part.startswith("sub-") and "." not in part:
                    subjects.append(part)

            stem = Path(path).stem
            for match in re.finditer(r"(?:^|_)sub-([^_]+)", stem):
                subjects.append(format_subject(match.group(1)))
            return subjects

        def recording_name(path: str) -> str:
            stem = Path(path).stem
            parts = stem.split("_")
            ignored_prefixes = ("sub", "ses", "param", "band")
            cleaned = [
                part
                for part in parts
                if part and not any(part.startswith(f"{prefix}-") for prefix in ignored_prefixes)
            ]
            return "_".join(cleaned) or stem

        def natural_key(value: str) -> list[Any]:
            return [int(part) if part.isdigit() else part.lower() for part in re.split(r"(\d+)", value)]

        subjects: list[str] = []
        recordings: list[str] = [recording_name(str(file_path)) for file_path in feature_files]

        selected_recordings = config_data.get("selected_recordings")
        if isinstance(selected_recordings, list):
            for recording in selected_recordings:
                if isinstance(recording, dict):
                    subject = recording.get("subject")
                    if subject:
                        subjects.append(format_subject(str(subject)))
                    source = recording.get("relative_path") or recording.get("path")
                    if source:
                        recordings.append(recording_name(str(source)))
                    for key in ("relative_path", "path"):
                        value = recording.get(key)
                        if value:
                            subjects.extend(subjects_from_path(str(value)))
                elif isinstance(recording, str):
                    recordings.append(recording_name(recording))
                    subjects.extend(subjects_from_path(recording))

        metadata = config_data.get("metadata")
        if isinstance(metadata, dict):
            metadata_subjects = metadata.get("subjects")
            if isinstance(metadata_subjects, list):
                subjects.extend(format_subject(str(subject)) for subject in metadata_subjects)
            if not recordings and metadata.get("task"):
                task = str(metadata["task"])
                recordings.append(task if task.startswith("task-") else f"task-{task}")

        for file_path in feature_files:
            subjects.extend(subjects_from_path(str(file_path)))

        self.state["plot_features_subjects"] = sorted(
            {subject for subject in subjects if subject.strip()},
            key=natural_key,
        )
        self.state["plot_features_recordings"] = sorted(
            {recording for recording in recordings if recording.strip()},
            key=natural_key,
        )

    @staticmethod
    def _extract_channel_names(config_data: dict[str, Any]) -> list[str]:
        metadata = config_data.get("metadata") if isinstance(config_data.get("metadata"), dict) else {}
        candidates = (
            metadata.get("channel_set"),
            metadata.get("channel_names"),
            metadata.get("channels"),
            config_data.get("channel_names"),
            config_data.get("channels"),
        )
        for candidate in candidates:
            if isinstance(candidate, list) and candidate:
                return [str(channel) for channel in candidate]
            if isinstance(candidate, tuple) and candidate:
                return [str(channel) for channel in candidate]
        return []

    @staticmethod
    def _format_value(value: Any) -> str:
        if isinstance(value, (list, tuple, set)):
            if not value:
                return "None"
            return ", ".join(str(item) for item in value)
        return str(value)

    def can_continue(self) -> bool:
        derivatives_path = self.state.get("derivatives_path")
        config_path = self.state.get("pipeline_config_path")
        return (
            bool(derivatives_path)
            and bool(config_path)
            and bool(self.state.get("channel_names"))
            and bool(self.state.get("analysis_mode"))
            and Path(str(derivatives_path)).is_dir()
            and Path(str(config_path)).is_file()
        )
